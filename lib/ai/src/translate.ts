import { z } from "zod";
import { chat } from "./chat";
import type { AiContext } from "./types";

const LANG_CODES = ["fr", "en", "wo", "ln", "ar", "auto"] as const;
export type LangCode = (typeof LANG_CODES)[number];

const LANG_LABELS: Record<Exclude<LangCode, "auto">, string> = {
  fr: "français",
  en: "anglais",
  wo: "wolof",
  ln: "lingala",
  ar: "arabe",
};

const DetectionSchema = z.object({
  language: z.string(),
  confidence: z.number().min(0).max(1).optional(),
});

const TranslationSchema = z.object({
  translation: z.string(),
  sourceLanguage: z.string().optional(),
});

export interface DetectLanguageOpts {
  ctx: AiContext;
  text: string;
}

/**
 * Detects the language of a free-form chat message. Returns one of the
 * supported codes ('fr', 'en', 'wo', 'ln', 'ar') or 'fr' as a safe fallback.
 */
export async function detectLanguage(opts: DetectLanguageOpts): Promise<string> {
  const sample = opts.text.trim().slice(0, 600);
  if (!sample) return "fr";
  const res = await chat({
    ctx: { ...opts.ctx, feature: opts.ctx.feature || "chat.detect_language" },
    messages: [
      {
        role: "system",
        content:
          "Tu es un détecteur de langue. Renvoie STRICTEMENT du JSON {\"language\":\"fr|en|wo|ln|ar\"} en choisissant le code ISO le plus proche parmi: fr (français), en (anglais), wo (wolof), ln (lingala), ar (arabe). Si tu n'es pas sûr, renvoie \"fr\".",
      },
      { role: "user", content: sample },
    ],
    jsonSchema: DetectionSchema,
    temperature: 0,
    maxTokens: 50,
  });
  const code = (res.content.language ?? "fr").toLowerCase();
  return ["fr", "en", "wo", "ln", "ar"].includes(code) ? code : "fr";
}

export interface TranslateOpts {
  ctx: AiContext;
  text: string;
  /** ISO code of the target language. */
  to: Exclude<LangCode, "auto">;
  /** Optional source-language hint. */
  from?: string;
}

/**
 * Translates `text` into the requested target language while preserving the
 * original meaning, register, and any formatting. Used for the multilingual
 * advisor↔student chat: the original is always kept; only the mirror is
 * generated by AI.
 */
export async function translateText(opts: TranslateOpts): Promise<string> {
  const targetLabel = LANG_LABELS[opts.to];
  const fromHint = opts.from && opts.from !== opts.to ? ` depuis le ${opts.from}` : "";
  const res = await chat({
    ctx: { ...opts.ctx, feature: opts.ctx.feature || "chat.translate" },
    messages: [
      {
        role: "system",
        content: `Tu traduis fidèlement des messages d'un échange étudiant↔conseiller pour un dossier visa étudiant France. Traduis le texte${fromHint} vers le ${targetLabel}. Conserve le ton et le sens. Renvoie STRICTEMENT du JSON: {"translation": "...", "sourceLanguage": "fr|en|wo|ln|ar"}.`,
      },
      { role: "user", content: opts.text },
    ],
    jsonSchema: TranslationSchema,
    temperature: 0.1,
    maxTokens: 1200,
  });
  return res.content.translation || opts.text;
}
